def analyze(depot_name, markers, W, H, sections):
    print(f"\n==================== {depot_name} (W={W}, H={H}) ====================")
    for sec in sections:
        matched = [m for m in markers if sec in m[0]]
        if not matched:
            print(f"No markers for {sec}")
            continue
        min_x = min(m[1] for m in matched)
        max_x = max(m[1] + m[3] for m in matched)
        min_y = min(m[2] for m in matched)
        max_y = max(m[2] + m[4] for m in matched)
        
        w = max_x - min_x
        h = max_y - min_y
        cx = (min_x + max_x) / 2
        cy = (min_y + max_y) / 2
        
        norm_x = cx / W
        norm_y = cy / H
        
        # Calculate optimal zoom to fit inside viewport
        # Suppose viewport is around 800x400 or mobile 400x300
        # Zoom factor = min(W / (w + padding), H / (h + padding))
        # But MAX_ZOOM in Angular is 2.2, here scale can be 2.0 - 3.5
        print(f"'{sec}':")
        print(f"  BBox: [{min_x:.1f}, {min_y:.1f}] to [{max_x:.1f}, {max_y:.1f}], Size: {w:.1f} x {h:.1f}")
        print(f"  Center: ({cx:.1f}, {cy:.1f}) -> OffsetData({norm_x:.3f}, {norm_y:.3f})")

