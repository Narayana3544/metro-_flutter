function Calc($name, $list, $W, $H, $sections) {
    Write-Output "=== $name (W=$W, H=$H) ==="
    foreach ($s in $sections) {
        $minX = 999999.0
        $maxX = -999999.0
        $minY = 999999.0
        $maxY = -999999.0
        $found = 0

        foreach ($item in $list) {
            if ($item.id -like "*$s*") {
                $found++
                $ix = [double]$item.x
                $iy = [double]$item.y
                $iw = [double]$item.w
                $ih = [double]$item.h
                if ($ix -lt $minX) { $minX = $ix }
                if (($ix + $iw) -gt $maxX) { $maxX = ($ix + $iw) }
                if ($iy -lt $minY) { $minY = $iy }
                if (($iy + $ih) -gt $maxY) { $maxY = ($iy + $ih) }
            }
        }

        if ($found -eq 0) { continue }
        $cx = ($minX + $maxX) / 2.0
        $cy = ($minY + $maxY) / 2.0
        $bw = $maxX - $minX
        $bh = $maxY - $minY
        $nx = [Math]::Round($cx / $W, 3)
        $ny = [Math]::Round($cy / $H, 3)

        Write-Output "'$s': OffsetData($nx, $ny), // BBox: [$minX, $minY] to [$maxX, $maxY], Size: $bw x $bh ($found slots)"
    }
}

